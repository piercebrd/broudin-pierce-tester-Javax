package com.parkit.parkingsystem.constants;

/**
 * This class defines the fare rates per hour for different vehicle types
 * in the Parkit parking system.

 * It provides constant values for the hourly rates of bikes and cars.

 * Note: This class should not be instantiated.
 */

public class Fare {

    /**
     * Hourly parking rate for bikes.
     */

    public static final double BIKE_RATE_PER_HOUR = 1.0;

    /**
     * Hourly parking rate for cars.
     */

    public static final double CAR_RATE_PER_HOUR = 1.5;
}
