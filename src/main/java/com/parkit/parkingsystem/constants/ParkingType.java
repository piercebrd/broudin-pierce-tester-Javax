package com.parkit.parkingsystem.constants;

/**
 * Enumeration representing the types of vehicles that can use the parking system.

 * This enum defines two types of parking: one for cars and one for bikes.

 */

public enum ParkingType {

    /**
     * Parking type for cars.
     */

    CAR,

    /**
     * Parking type for bikes.
     */

    BIKE
}
